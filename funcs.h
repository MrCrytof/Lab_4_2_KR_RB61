#ifndef FUNCS_H
#define FUNCS_H

#include <stdio.h>
#include <stdlib.h>

/**
 * @brief Виділяє динамічну пам'ять для двовимірної матриці.
 *
 * @param rows Кількість рядків матриці.
 * @param cols Кількість стовпців матриці.
 * @return int** Вказівник на матрицю або NULL у разі помилки.
 */
int** memory_allocation(int rows, int cols);

/**
 * @brief Звільняє динамічно виділену пам'ять матриці.
 *
 * @param matrix Вказівник на матрицю.
 * @param rows Кількість рядків матриці.
 */
void clearMemory(int** matrix, int rows);

/**
 * @brief Виводить матрицю на екран.
 *
 * @param matrix Вказівник на матрицю.
 * @param rows Кількість рядків матриці.
 * @param cols Кількість стовпців матриці.
 */
void print_matrix(int** matrix, int rows, int cols);

/**
 * @brief Заповнює матрицю одним із запропонованих способів.
 *
 * @details Підтримує ручне введення, заповнення випадковими числами
 * та заповнення за формулою A[i][j] = i + j.
 *
 * @param matrix Вказівник на матрицю.
 * @param rows Кількість рядків матриці.
 * @param cols Кількість стовпців матриці.
 */
void fill_matrix(int** matrix, int rows, int cols, char matrix_name);

/**
 * @brief Знаходить максимальний і мінімальний елементи вище головної діагоналі.
 *
 * @details Розглядає лише елементи, індекс стовпця яких більший
 * за індекс рядка (j > i).
 *
 * @param A Вказівник на квадратну матрицю A.
 * @param r_a Кількість рядків і стовпців матриці A.
 * @param max_a Вказівник для збереження максимального елемента.
 * @param min_a Вказівник для збереження мінімального елемента.
 */
void max_min(int** A, int r_a, int* max_a, int* min_a);

/**
 * @brief Створює транспоновану матрицю B.
 *
 * @details Рядки вихідної матриці стають стовпцями транспонованої.
 *
 * @param B Вказівник на вихідну матрицю B.
 * @param r_b Кількість рядків матриці B.
 * @param c_b Кількість стовпців матриці B.
 * @return int** Вказівник на транспоновану матрицю або NULL у разі помилки.
 */
int** transpose(int** B, int r_b, int c_b);

/**
 * @brief Обчислює добуток двох матриць A і B.
 *
 * @details Кількість стовпців матриці A має дорівнювати
 * кількості рядків матриці B.
 *
 * @param A Вказівник на першу матрицю.
 * @param r_a Кількість рядків матриці A.
 * @param c_a Кількість стовпців матриці A.
 * @param B Вказівник на другу матрицю.
 * @param r_b Кількість рядків матриці B.
 * @param c_b Кількість стовпців матриці B.
 * @return int** Вказівник на матрицю добутку або NULL у разі помилки.
 */
int** mult_a_b(int** A, int r_a, int c_a, int** B, int r_b, int c_b);

/**
 * @brief Сортує елементи квадратної матриці A за зростанням.
 *
 * @details Режим 1 сортує всі елементи матриці,
 * режим 2 сортує лише вказаний рядок.
 *
 * @param A Вказівник на квадратну матрицю A.
 * @param n Кількість рядків і стовпців матриці A.
 * @param mode Режим сортування: 1 — уся матриця, 2 — окремий рядок.
 * @param row_index Індекс рядка для сортування, якщо mode == 2.
 */
void sort_matrix(int** A, int n, int mode, int row_index);

/**
 * @brief Обчислює та виводить суми елементів рядків матриці A
 * і стовпців матриці B.
 *
 * @param A Вказівник на матрицю A.
 * @param r_a Кількість рядків матриці A.
 * @param c_a Кількість стовпців матриці A.
 * @param B Вказівник на матрицю B.
 * @param r_b Кількість рядків матриці B.
 * @param c_b Кількість стовпців матриці B.
 */
void print_sums(int** A, int r_a, int c_a, int** B, int r_b, int c_b);

#endif // FUNCS_H
